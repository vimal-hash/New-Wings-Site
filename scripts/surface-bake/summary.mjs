// docs/restoration/README.md: per-item runtime bytes, dimensions, GPU estimate and status, from the live manifest.
import fs from 'node:fs';
const cfg=JSON.parse(fs.readFileSync('scripts/surface-bake/items.json'));
const manifest=JSON.parse(fs.readFileSync('components/corridor/baked-surfaces.json'));
const mib=b=>(b/1048576).toFixed(2);
let bytes=0,gpu=0,files=0;
const rows=manifest.items.map(e=>{
  const s=cfg.items[e.item],size=e.imageSize??e.atlas,g=size[0]*size[1]*4/3;
  if(e.active){bytes+=e.bytes.texture+e.bytes.uv;gpu+=g;files+=2;}
  return `| [${(s.title??e.item).replaceAll("|","\\|")}](../${e.item}-audit/README.md) | ${e.active?'active':'inactive'} | ${size.join("x")} | ${e.bytes.texture.toLocaleString('en-GB')} | ${e.bytes.uv.toLocaleString('en-GB')} | ${mib(g)} | ${s.status??'not verified'} |`;
});
const ceiling=JSON.parse(fs.readFileSync('components/corridor/theatre-ceiling-assets.json')),leftWall=JSON.parse(fs.readFileSync('components/corridor/theatre-left-wall-assets.json'));
const accepted=[['Ceiling (own component, 6K)',fs.statSync('public'+ceiling.texture).size+fs.statSync('public'+ceiling.model).size],
  ['Left wall (own component, 6K)',fs.statSync('public'+leftWall.texture).size]];
const md=`# Theatre and corridor restoration — summary

Generated by \`node scripts/surface-bake/summary.mjs\` from \`components/corridor/baked-surfaces.json\`.
Inventory, classification and the corridor finding: [inventory.md](inventory.md). Protected hashes: \`node scripts/restoration-baseline.mjs --check\`.

| Item | Runtime | Atlas | KTX2 bytes | UV sidecar bytes | GPU est. MiB | Status |
|---|---|---|---:|---:|---:|---|
${rows.join('\n')}

New runtime files: ${files} (one KTX2 + one chart sidecar per item). New download: **${bytes.toLocaleString('en-GB')} bytes** (${mib(bytes)} MiB).
Estimated GPU memory for the new atlases (UASTC transcoded to 4x4-block formats, 1 byte/texel, with mips): **${mib(gpu)} MiB**.
Drawn by their own components (not in the manifest): ${accepted.map(([n,b])=>`${n} ${b.toLocaleString('en-GB')} bytes`).join('; ')}.

GPU figures are estimates; on devices without BC7/ASTC support the transcoder falls back to other formats (ETC2/RGBA) that can use more memory.
`;
fs.writeFileSync('docs/restoration/README.md',md);console.log('SUMMARY',files,bytes,Math.round(gpu));
